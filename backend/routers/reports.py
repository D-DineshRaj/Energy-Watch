"""Router for consumption reports, statement generation, and CSV export."""
from datetime import datetime, timezone
from typing import Optional
from fastapi import APIRouter, Depends, HTTPException, Query, Response
from sqlalchemy.orm import Session

from backend.database import get_db
from backend.schemas import (
    ReportSummaryResponse,
    StatementResponse,
)
from backend.services.reports import (
    generate_consumption_summary,
    generate_readings_csv,
)

router = APIRouter()


@router.get("/reports/summary", response_model=ReportSummaryResponse)
def get_consumption_report(
    start_date: Optional[str] = Query(None, description="Report start date (YYYY-MM-DD)"),
    end_date: Optional[str] = Query(None, description="Report end date (YYYY-MM-DD)"),
    meter_id: Optional[str] = Query("EW-2847-HH", description="Smart meter identifier"),
    sanctioned_load_kw: float = Query(1.0, description="Sanctioned connected load in kW"),
    db: Session = Depends(get_db),
):
    """Generate daily/monthly electricity consumption summary with APERC bill estimates."""
    try:
        summary = generate_consumption_summary(
            db=db,
            start_date=start_date,
            end_date=end_date,
            meter_id=meter_id,
            sanctioned_load_kw=sanctioned_load_kw,
        )
        return summary
    except ValueError as err:
        raise HTTPException(status_code=400, detail=str(err))


@router.get("/reports/export-csv")
def export_readings_csv(
    start_date: Optional[str] = Query(None, description="Filter start date (YYYY-MM-DD)"),
    end_date: Optional[str] = Query(None, description="Filter end date (YYYY-MM-DD)"),
    meter_id: Optional[str] = Query("EW-2847-HH", description="Smart meter identifier"),
    db: Session = Depends(get_db),
):
    """Export filtered meter readings as a downloadable RFC-4180 CSV file."""
    try:
        csv_content, filename, count = generate_readings_csv(
            db=db,
            start_date=start_date,
            end_date=end_date,
            meter_id=meter_id,
        )
        return Response(
            content=csv_content,
            media_type="text/csv",
            headers={
                "Content-Disposition": f'attachment; filename="{filename}"',
                "X-Total-Rows": str(count),
            },
        )
    except ValueError as err:
        raise HTTPException(status_code=400, detail=str(err))


@router.get("/reports/statement", response_model=StatementResponse)
def get_energy_statement(
    start_date: Optional[str] = Query(None, description="Statement start date (YYYY-MM-DD)"),
    end_date: Optional[str] = Query(None, description="Statement end date (YYYY-MM-DD)"),
    meter_id: Optional[str] = Query("EW-2847-HH", description="Smart meter identifier"),
    sanctioned_load_kw: float = Query(1.0, description="Sanctioned load in kW"),
    db: Session = Depends(get_db),
):
    """Generate formal utility consumption statement with APERC telescopic breakdown for printing/PDF."""
    try:
        summary = generate_consumption_summary(
            db=db,
            start_date=start_date,
            end_date=end_date,
            meter_id=meter_id,
            sanctioned_load_kw=sanctioned_load_kw,
        )
        s_date = summary["start_date"].replace("-", "")
        e_date = summary["end_date"].replace("-", "")
        stmt_id = f"EW-STMT-{meter_id or 'EW-2847-HH'}-{s_date}-{e_date}"

        return StatementResponse(
            statement_id=stmt_id,
            statement_date=datetime.now().strftime("%Y-%m-%d"),
            consumer_name="Household Consumer (Simulated)",
            meter_id=summary["meter_id"],
            period_start=summary["start_date"],
            period_end=summary["end_date"],
            days_in_period=summary["days_count"],
            total_kwh=summary["total_consumption_kwh"],
            daily_avg_kwh=summary["daily_avg_kwh"],
            peak_day=summary["peak_day"],
            peak_day_kwh=summary["peak_day_kwh"],
            bill_estimate=summary["bill_breakdown"],
            daily_breakdown=summary["daily_breakdown"],
            is_official=False,
            disclaimer=(
                "INFORMATIONAL STATEMENT ONLY: This energy statement is generated by EnergyWatch "
                "using recorded simulated meter readings and APERC FY 2026-27 telescopic tariff rules. "
                "It is designed for household budgeting and energy management. Official monthly electricity "
                "bills are issued exclusively by state electricity distribution utilities."
            ),
        )
    except ValueError as err:
        raise HTTPException(status_code=400, detail=str(err))
